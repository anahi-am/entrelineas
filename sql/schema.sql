-- Minimal Supabase schema for the housing MVP.
-- Run through a reviewed migration; do not expose service-role keys to clients.

create table if not exists promises (
  id text primary key,
  party text not null,
  text text not null,
  source_url text not null,
  topic text not null check (topic = 'vivienda'),
  territory text not null,
  created_at timestamptz not null default now()
);

create table if not exists boe_items (
  id text primary key,
  date date not null,
  title text not null,
  original_url text not null,
  raw_text text not null default '',
  simplified_text text not null default '',
  topics text[] not null default '{}',
  territory text not null check (territory = 'Estatal'),
  retrieved_at timestamptz not null default now()
);

create table if not exists evidence_links (
  id bigint generated by default as identity primary key,
  promise_id text not null references promises(id),
  boe_item_id text not null references boe_items(id),
  status text not null check (status in ('hecho', 'en_tramite', 'bloqueada', 'sin_rastro')),
  reasoning text not null,
  reviewed_at timestamptz,
  reviewer text,
  unique (promise_id, boe_item_id)
);
